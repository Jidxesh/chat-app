// Message status ticks
export function Ticks({ status }) {
  if (status === 'pending') {
    return (
      <svg className="tick" width="14" height="14" viewBox="0 0 16 16" aria-label="Sending">
        <circle cx="8" cy="8" r="6.2" fill="none" stroke="currentColor" strokeWidth="1.4" />
        <path d="M8 4.5V8l2.3 1.6" fill="none" stroke="currentColor" strokeWidth="1.4" strokeLinecap="round" />
      </svg>
    )
  }
  if (status === 'failed') return <span className="tick tick-failed" aria-label="Failed">!</span>
  const double = status !== 'sent'
  return (
    <svg
      className={`tick ${status === 'read' ? 'tick-read' : ''}`}
      width="16"
      height="11"
      viewBox="0 0 16 11"
      aria-label={status}
    >
      <path d="M11.07.65 4.5 7.23 1.93 4.66.87 5.72 4.5 9.35l7.63-7.64z" fill="currentColor" />
      {double && <path d="M15.13.65 8.56 7.23l-.75-.75-1.06 1.06 1.81 1.81 7.63-7.64z" fill="currentColor" />}
    </svg>
  )
}

